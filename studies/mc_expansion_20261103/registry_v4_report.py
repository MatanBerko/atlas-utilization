#!/usr/bin/env python
"""Registry v4 check report (task A1 step 2), incl. the LIVE portal comparison (2b).

Reads the v4 registry, compares every portal value used (generator factors, the three W values
inside the W k-factor, and the LO DY 5396 of MiniAOD 35670) with the saved copy AND with the live
CERN Open Data API (if reachable), and writes evidence/registry_v4_checks.json and
REGISTRY_CHECKS.md (tables for a-d). Run:  python studies/mc_expansion_20261103/registry_v4_report.py
"""
from __future__ import annotations

import json
import math
import pathlib
import sys
import time
import urllib.request

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO))
from studies.cms_mc_weights_v3.tests import test_registry_v4 as T  # noqa: E402

API = "https://opendata.cern.ch/api/records/{}"


def live(mini):
    for attempt in range(3):
        try:
            with urllib.request.urlopen(API.format(mini), timeout=60) as r:
                return json.load(r)["metadata"].get("cross_section", {}).get("total_value")
        except Exception as e:  # noqa: BLE001
            err = repr(e)
            time.sleep(2)
    return f"UNREACHABLE: {err}"


def main():
    new = T.new_records()
    vals = sorted(set((m, v) for _, m, v in T.portal_values()) | {(69714, 53300.0), (69716, 8958.0), (69718, 3330.0), (35670, 5396.0)})
    portal = []
    for mini, v in vals:
        saved = float(T.rec(mini)["cross_section"]["total_value"])
        lv = live(mini)
        lvf = float(lv) if isinstance(lv, str) and not lv.startswith("UNREACHABLE") else None
        portal.append({"mini": mini, "used": v, "saved": saved, "live": lv,
                       "saved_ok": saved == v, "live_ok": (lvf == v) if lvf is not None else None})
    sig = []
    for rid, r in sorted(new.items(), key=lambda kv: (kv[1]["tier"], kv[0])):
        prod = math.prod(f["value"] for f in r["decision_2026_11_03"]["factors"])
        m = T.MATAN_FINAL.get(rid)
        sig.append({"nano": rid, "mini": r["mini_recid"], "tier": r["tier"], "name": r["physics_short"],
                    "registry": r["cross_section_pb"], "matan": m[1] if m else None, "product": prod,
                    "rel_diff": prod / r["cross_section_pb"] - 1, "in_full_run": r["in_full_run"],
                    "verification": r["decision_2026_11_03"]["verification"]})
    tau = T.tau_table()
    res = {"generated": time.strftime("%Y-%m-%d %H:%M %Z"), "portal": portal, "sigma": sig, "tau": tau}
    (HERE / "evidence").mkdir(exist_ok=True)
    (HERE / "evidence" / "registry_v4_checks.json").write_text(json.dumps(res, indent=1) + "\n")

    L = ["# Registry v4 checks (task A1 step 2, 3 Nov 2026)", "",
         "Generated by `registry_v4_report.py` (VERIFIED BY RUNNING); the same checks run as tests in",
         "`studies/cms_mc_weights_v3/tests/test_registry_v4.py`. Raw: `evidence/registry_v4_checks.json`.", "",
         "## a. σ_eff recomputed from its factors", "",
         f"{len(sig)} new records (54 in the full run + 4 ON HOLD). Largest |product / listed − 1| = "
         f"{max(abs(s['rel_diff']) for s in sig):.1e} (limit 1e-4). Every in-full-run value equals Matan's list exactly.", "",
         "| tier | NanoAOD | MiniAOD | sample | σ_eff [pb] | product of factors | rel. diff | verification |", "|---:|---|---|---|---:|---:|---:|---|"]
    for s in sig:
        L.append(f"| {s['tier']} | {s['nano']} | {s['mini']} | {s['name']} | {s['registry']:.6g} | {s['product']:.6g} | {s['rel_diff']:+.1e} | "
                 f"{s['verification'] if s['in_full_run'] else 'ON HOLD (in_full_run false)'} |")
    nl = sum(1 for p in portal if p["live_ok"] is True)
    L += ["", "## b. Portal values: saved copy and live API", "",
          f"{len(portal)} MiniAOD values. Saved copy equal: {sum(p['saved_ok'] for p in portal)}/{len(portal)}. "
          f"Live API equal: {nl}/{len(portal)}" + ("" if nl == len(portal) else " — see the table") + ".", "",
          "| MiniAOD | value used | saved copy | live API (read now) | result |", "|---|---:|---:|---:|---|"]
    for p in portal:
        res_ = "OK" if p["saved_ok"] and p["live_ok"] else ("live not reachable" if p["live_ok"] is None else "DIFFERENCE")
        L.append(f"| {p['mini']} | {p['used']:g} | {p['saved']:g} | {p['live']} | {res_} |")
    L += ["", "## c. τ-inclusion check (generator cards vs the leptonic BR factor)", "",
          "| sample | card evidence | factor used | result |", "|---|---|---|---|"]
    for t in tau:
        L.append(f"| {t['sample']} | {t['card_evidence']} | {t['factor']} | {t['result']} |")
    L += ["", "Plus 67841 TTToHadronic: POWHEG `topdecaymode 00022` (both W → quarks) ↔ BR(W → had)² — OK.",
          "JHUGen DecayMode meanings are from the JHUGen master source comment (lines 357-368); the samples used v7.x (UNVERIFIED for that exact version, as in the plan).", "",
          "## d. Duplicates and overlaps", "",
          "- 73 records, none twice; the 15 v3 records are carried over as identical dicts (13 in the full run + 35671, 42407 not).",
          "- Full run = the 13 delivered + the 54 new; not in the full run = 35671, 42407 (v3) + the 4 ON HOLD.",
          "- No new record is a delivered record; none is in the excluded list.",
          "- W+jets: the three NLO pieces only; the inclusive 69745 / 69747 are excluded (pieces exclusive by Born parton count, D1).",
          "- tt̄ decay split: (67801 + 67993 + 67841) / 833.9 = 1.0026 (the PDG convention's known +0.26 %).",
          "- Tribosons: ext1 records only (72702, 72712, 72762, 75601 are not in the registry).",
          "- qq → ZH samples (41914, 74684, 74682, 74292) use 'all but gg → ZH' 0.7612; gg → ZH (40095, 40062) 0.1227.",
          "- Dropped / deferred records are listed as deliberately excluded: 35999, 35987, 35993 (E2), 64793, 64693 (D4), 68833, 74314 and the six Dalitz records (D13), 69745, 69747 (D1).",
          "- 75567 moved from v3's excluded list into the registry (D14, LHE check of 3 Nov).",
          "- k_factor = gen_filt_eff = 1.0 and sum_of_weights = null for all 73; only 40062 carries `estimate: true`.", ""]
    (HERE / "REGISTRY_CHECKS.md").write_text("\n".join(L))
    print(f"portal saved ok {sum(p['saved_ok'] for p in portal)}/{len(portal)}, live ok {nl}/{len(portal)}; tau "
          f"{sum(t['result'] == 'OK' for t in tau)}/{len(tau)} OK")
    bad = [p for p in portal if p["live_ok"] is False or not p["saved_ok"]]
    if bad:
        print("DIFFERENCES:", bad)


if __name__ == "__main__":
    main()
